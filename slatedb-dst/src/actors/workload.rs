const WORKLOAD_VALUE_VERSION_SIZE: usize = size_of::<u64>();

/// Configuration for the mixed DST workload actor.
#[derive(Clone, Debug)]
pub struct WorkloadActorOptions {
    /// Number of logical keys each actor maps random samples onto under its
    /// `{name}/` prefix.
    pub key_count: usize,
    /// Minimum random value size generated for `put`, `merge`, and `write_batch`.
    pub min_value_size: usize,
    /// Maximum random value size generated for `put`, `merge`, and `write_batch`.
    pub max_value_size: usize,
    /// Durability level used by workload read verification.
    pub read_durability: DurabilityLevel,
    /// Relative weights for selecting each workload operation.
    pub operation_weights: WorkloadOperationWeights,
}

impl Default for WorkloadActorOptions {
    fn default() -> Self {
        Self {
            key_count: 1024,
            min_value_size: 32,
            max_value_size: 256,
            read_durability: DurabilityLevel::Memory,
            operation_weights: WorkloadOperationWeights::default(),
        }
    }
}

/// Relative operation weights. A zero weight disables an operation.
///
/// All weights default to one. The actor ignores the merge weight when no merge
/// operator is configured. At least one enabled operation must have a positive weight.
/// These weights select whole operations; they do not change entries inside write batches.
#[derive(Clone, Debug)]
pub struct WorkloadOperationWeights {
    /// Weight for point reads.
    pub get: u32,
    /// Weight for prefix scans.
    pub scan: u32,
    /// Weight for deletes.
    pub delete: u32,
    /// Weight for puts.
    pub put: u32,
    /// Weight for merges, when a merge operator is configured.
    pub merge: u32,
    /// Weight for write batches with random put, delete, and optional merge entries.
    pub write_batch: u32,
}

impl Default for WorkloadOperationWeights {
    fn default() -> Self {
        Self {
            get: 1,
            scan: 1,
            delete: 1,
            put: 1,
            merge: 1,
            write_batch: 1,
        }
    }
}

impl WorkloadOperationWeights {
    fn operations(&self, merge_enabled: bool) -> [(WorkloadOperation, u32); 6] {
        [
            (WorkloadOperation::Get, self.get),
            (WorkloadOperation::Scan, self.scan),
            (WorkloadOperation::Delete, self.delete),
            (WorkloadOperation::Put, self.put),
            (
                WorkloadOperation::Merge,
                if merge_enabled { self.merge } else { 0 },
            ),
            (WorkloadOperation::WriteBatch, self.write_batch),
        ]
    }

    fn sample(&self, rand_value: u64, merge_enabled: bool) -> Result<WorkloadOperation, Error> {
        let operations = self.operations(merge_enabled);
        let total: u64 = operations
            .iter()
            .map(|(_, weight)| u64::from(*weight))
            .sum();
        if total == 0 {
            return Err(Error::invalid(
                "workload actor has no enabled operation with a positive weight".into(),
            ));
        }

        // Keep the operation order and one random draw used by the default workload.
        let mut ticket = rand_value % total;
        for (operation, weight) in operations {
            let weight = u64::from(weight);
            if ticket < weight {
                return Ok(operation);
            }
            ticket -= weight;
        }
        unreachable!("workload operation weights cover every ticket")
    }
}

/// Merge operator for values generated by [`WorkloadActor`].
///
/// Workload values encode a big-endian `u64` version in the first eight bytes
/// and treat the remaining bytes as opaque payload. Merge resolution returns
/// the value with the highest encoded version (an associative operation, which
/// is required for correct merge behavior).
#[derive(Debug, Default)]
pub struct WorkloadMergeOperator;

impl MergeOperator for WorkloadMergeOperator {
    fn merge(
        &self,
        key: &Bytes,
        existing_value: Option<Bytes>,
        value: Bytes,
    ) -> Result<Bytes, MergeOperatorError> {
        self.merge_batch(key, existing_value, std::slice::from_ref(&value))
    }

    fn merge_batch(
        &self,
        _key: &Bytes,
        existing_value: Option<Bytes>,
        operands: &[Bytes],
    ) -> Result<Bytes, MergeOperatorError> {
        existing_value
            .into_iter()
            .chain(operands.iter().cloned())
            .max_by_key(|value| decode_workload_value(value.as_ref()))
            .ok_or(MergeOperatorError::EmptyBatch)
    }
}

#[derive(Debug)]
pub struct WorkloadActor {
    options: WorkloadActorOptions,
    observed: BTreeMap<Bytes, Observation>,
    next_value_version: AtomicU64,
    step: u64,
    key_prefix: Option<String>,
}

#[derive(Clone, Copy, Debug)]
struct Observation {
    max_seen_version: u64,
    observed_absent: bool,
}

impl WorkloadActor {
    pub fn new(options: WorkloadActorOptions) -> Result<Self, Error> {
        assert!(
            options.key_count > 0,
            "workload actor key_count must be greater than zero"
        );
        assert!(
            options.min_value_size <= options.max_value_size,
            "workload actor min_value_size must be less than or equal to max_value_size"
        );
        assert!(
            options.max_value_size >= WORKLOAD_VALUE_VERSION_SIZE,
            "workload actor max_value_size must be at least {WORKLOAD_VALUE_VERSION_SIZE} bytes"
        );
        if options
            .operation_weights
            .operations(true)
            .iter()
            .all(|(_, weight)| *weight == 0)
        {
            return Err(Error::invalid(
                "workload actor needs at least one positive operation weight".into(),
            ));
        }

        Ok(Self {
            options,
            observed: BTreeMap::new(),
            next_value_version: AtomicU64::new(1),
            step: 0,
            key_prefix: None,
        })
    }

    /// Overrides the version assigned to the next generated workload value.
    pub fn with_next_value_version(mut self, next_value_version: u64) -> Self {
        self.next_value_version = AtomicU64::new(next_value_version);
        self
    }
}

#[derive(Clone, Copy, Debug, Eq, PartialEq)]
enum WorkloadOperation {
    Get,
    Scan,
    Delete,
    Put,
    Merge,
    WriteBatch,
}

#[async_trait]
impl Actor for WorkloadActor {
    /// Executes one mixed deterministic workload step against the shared
    /// database while verifying reads against actor-local monotonic observations.
    #[instrument(level = "debug", skip_all, fields(name = %ctx.name()))]
    async fn run(&mut self, ctx: &ActorCtx) -> Result<(), Error> {
        let put_options = PutOptions::default();
        let write_options = WriteOptions {
            ..WriteOptions::default()
        };
        let key_prefix = self
            .key_prefix
            .get_or_insert_with(|| format!("{}/", ctx.name()))
            .clone();
        let merge_enabled = ctx.merge_operator().is_some();
        let operation = self
            .options
            .operation_weights
            .sample(ctx.rand().rng().next_u64(), merge_enabled)?;

        match operation {
            WorkloadOperation::Get => {
                let key = workload_key(
                    &key_prefix,
                    ctx.rand().rng().next_u64(),
                    self.options.key_count,
                );
                verify_get(
                    ctx,
                    self.step,
                    &key,
                    self.options.read_durability,
                    &mut self.observed,
                )
                .await?;
            }
            WorkloadOperation::Scan => {
                verify_scan(
                    ctx,
                    self.step,
                    &key_prefix,
                    self.options.read_durability,
                    &mut self.observed,
                )
                .await?;
            }
            WorkloadOperation::Delete => {
                let key = workload_key(
                    &key_prefix,
                    ctx.rand().rng().next_u64(),
                    self.options.key_count,
                );
                ctx.db()
                    .delete_with_options(key.clone(), &write_options)
                    .await?;
            }
            WorkloadOperation::Put => {
                let key = workload_key(
                    &key_prefix,
                    ctx.rand().rng().next_u64(),
                    self.options.key_count,
                );
                let version = self.next_value_version.fetch_add(1, Ordering::Relaxed);
                let value = workload_value(
                    version,
                    &mut *ctx.rand().rng(),
                    self.options.min_value_size,
                    self.options.max_value_size,
                );
                ctx.db()
                    .put_with_options(key.clone(), value, &put_options, &write_options)
                    .await?;
            }
            WorkloadOperation::Merge => {
                let key = workload_key(
                    &key_prefix,
                    ctx.rand().rng().next_u64(),
                    self.options.key_count,
                );
                let version = self.next_value_version.fetch_add(1, Ordering::Relaxed);
                let value = workload_value(
                    version,
                    &mut *ctx.rand().rng(),
                    self.options.min_value_size,
                    self.options.max_value_size,
                );
                ctx.db()
                    .merge_with_options(
                        key.clone(),
                        value,
                        &MergeOptions::default(),
                        &write_options,
                    )
                    .await?;
            }
            WorkloadOperation::WriteBatch => {
                let mut batch = WriteBatch::new();
                let batch_len = 2 + (ctx.rand().rng().next_u64() % 3) as usize;

                for _ in 0..batch_len {
                    let key = workload_key(
                        &key_prefix,
                        ctx.rand().rng().next_u64(),
                        self.options.key_count,
                    );
                    let sampled_operation_count = if merge_enabled { 3 } else { 2 };
                    let sampled_operation = {
                        let mut rng = ctx.rand().rng();
                        rng.next_u64() % sampled_operation_count
                    };
                    match sampled_operation {
                        0 => {
                            let version = self.next_value_version.fetch_add(1, Ordering::Relaxed);
                            let value = workload_value(
                                version,
                                &mut *ctx.rand().rng(),
                                self.options.min_value_size,
                                self.options.max_value_size,
                            );
                            batch.put_bytes(key.clone(), value);
                        }
                        1 => batch.delete(key.clone()),
                        _ => {
                            let version = self.next_value_version.fetch_add(1, Ordering::Relaxed);
                            let value = workload_value(
                                version,
                                &mut *ctx.rand().rng(),
                                self.options.min_value_size,
                                self.options.max_value_size,
                            );
                            batch.merge(key.clone(), value);
                        }
                    }
                }

                ctx.db().write_with_options(batch, &write_options).await?;
            }
        }

        self.step += 1;
        if self.step % PROGRESS_LOG_INTERVAL == 0 {
            info!(
                "workload step complete [name={}, step={}, observed_keys={}]",
                ctx.name(),
                self.step,
                self.observed.len()
            );
        }

        Ok(())
    }
}

fn workload_key(prefix: &str, rand_value: u64, key_count: usize) -> Bytes {
    let key_index = ((rand_value >> 8) as usize) % key_count;
    Bytes::from(format!("{prefix}{key_index}"))
}

fn workload_value(
    version: u64,
    rng: &mut impl Rng,
    min_value_size: usize,
    max_value_size: usize,
) -> Bytes {
    let min_value_size = min_value_size.max(WORKLOAD_VALUE_VERSION_SIZE);
    let value_len =
        min_value_size + (rng.next_u64() as usize % (max_value_size - min_value_size + 1));
    let mut value = vec![0; value_len];
    value[..WORKLOAD_VALUE_VERSION_SIZE].copy_from_slice(&version.to_be_bytes());
    rng.fill_bytes(&mut value[WORKLOAD_VALUE_VERSION_SIZE..]);
    Bytes::from(value)
}

async fn verify_get(
    ctx: &ActorCtx,
    step: u64,
    key: &Bytes,
    read_durability: DurabilityLevel,
    observed: &mut BTreeMap<Bytes, Observation>,
) -> Result<(), Error> {
    let read_options = ReadOptions::new().with_durability_filter(read_durability);
    match ctx
        .db()
        .get_with_options(key.clone(), &read_options)
        .await?
    {
        Some(value) => observe_present(ctx, step, key, &value, observed),
        None => observe_absent(key, observed),
    }
    Ok(())
}

async fn verify_scan(
    ctx: &ActorCtx,
    step: u64,
    key_prefix: &str,
    read_durability: DurabilityLevel,
    observed: &mut BTreeMap<Bytes, Observation>,
) -> Result<(), Error> {
    let scan_options = build_scan_options(ctx.rand(), read_durability);
    let mut iter = ctx
        .db()
        .scan_prefix_with_options(key_prefix.as_bytes(), .., &scan_options)
        .await?;
    let mut seen = BTreeSet::new();
    let mut previous_key: Option<Bytes> = None;

    while let Some(key_value) = iter.next().await? {
        assert!(
            key_value.key.starts_with(key_prefix.as_bytes()),
            "workload scan returned key outside prefix [name={}, step={}, key_prefix={}, key={}]",
            ctx.name(),
            step,
            key_prefix,
            String::from_utf8_lossy(key_value.key.as_ref()).into_owned(),
        );
        assert!(
            seen.insert(key_value.key.clone()),
            "workload scan returned duplicate key [name={}, step={}, key_prefix={}, key={}]",
            ctx.name(),
            step,
            key_prefix,
            String::from_utf8_lossy(key_value.key.as_ref()).into_owned(),
        );
        if let Some(previous_key) = previous_key.as_ref() {
            let is_ordered = match scan_options.order {
                IterationOrder::Ascending => previous_key < &key_value.key,
                IterationOrder::Descending => previous_key > &key_value.key,
            };
            assert!(
                is_ordered,
                "workload scan returned keys out of order [name={}, step={}, key_prefix={}, order={:?}, previous_key={}, key={}]",
                ctx.name(),
                step,
                key_prefix,
                scan_options.order,
                String::from_utf8_lossy(previous_key.as_ref()),
                String::from_utf8_lossy(key_value.key.as_ref()),
            );
        }
        previous_key = Some(key_value.key.clone());
        observe_present(ctx, step, &key_value.key, &key_value.value, observed);
    }

    let missing_keys = observed
        .keys()
        .filter(|key| key.starts_with(key_prefix.as_bytes()) && !seen.contains(*key))
        .cloned()
        .collect::<Vec<_>>();
    for key in missing_keys {
        observe_absent(&key, observed);
    }

    Ok(())
}

fn observe_present(
    ctx: &ActorCtx,
    step: u64,
    key: &Bytes,
    value: &Bytes,
    observed: &mut BTreeMap<Bytes, Observation>,
) {
    let version = decode_workload_value(value.as_ref());
    let key_display = String::from_utf8_lossy(key.as_ref()).into_owned();
    match observed.get_mut(key) {
        Some(observation) => {
            assert!(
                !(observation.observed_absent && version <= observation.max_seen_version),
                "workload read stale value after observed deletion [name={}, step={}, key={}, version={}, max_seen_version={}]",
                ctx.name(),
                step,
                key_display,
                version,
                observation.max_seen_version,
            );
            assert!(
                version >= observation.max_seen_version,
                "workload read version moved backward [name={}, step={}, key={}, version={}, max_seen_version={}]",
                ctx.name(),
                step,
                key_display,
                version,
                observation.max_seen_version,
            );
            observation.max_seen_version = version;
            observation.observed_absent = false;
        }
        None => {
            observed.insert(
                key.clone(),
                Observation {
                    max_seen_version: version,
                    observed_absent: false,
                },
            );
        }
    }
}

fn observe_absent(key: &Bytes, observed: &mut BTreeMap<Bytes, Observation>) {
    if let Some(observation) = observed.get_mut(key) {
        observation.observed_absent = true;
    }
}

pub(crate) fn decode_workload_value(value: &[u8]) -> u64 {
    let version_bytes: [u8; WORKLOAD_VALUE_VERSION_SIZE] = value[..WORKLOAD_VALUE_VERSION_SIZE]
        .try_into()
        .expect("workload value version slice has fixed size");
    u64::from_be_bytes(version_bytes)
}

#[cfg(test)]
mod tests {
    use std::sync::Arc;

    use slatedb::config::Settings;
    use slatedb::{DbRand, ErrorKind};

    use super::*;
    use crate::Harness;
    use WorkloadOperation::{Delete, Get, Merge, Put, Scan, WriteBatch};

    const NO_OPERATIONS: WorkloadOperationWeights = WorkloadOperationWeights {
        get: 0,
        scan: 0,
        delete: 0,
        put: 0,
        merge: 0,
        write_batch: 0,
    };

    #[test]
    fn test_default_weights_preserve_operation_sequence() {
        let weights = WorkloadOperationWeights::default();
        for seed in [0, 7, u64::MAX] {
            for (merge_enabled, expected) in [
                (false, vec![Get, Scan, Delete, Put, WriteBatch]),
                (true, vec![Get, Scan, Delete, Put, Merge, WriteBatch]),
            ] {
                let rand = DbRand::new(seed);
                for _ in 0..100 {
                    let value = rand.rng().next_u64();
                    assert_eq!(
                        weights.sample(value, merge_enabled).unwrap(),
                        expected[(value % expected.len() as u64) as usize],
                    );
                }
            }
        }
    }

    #[test]
    fn test_operation_weights_select_expected_intervals() {
        let weights = WorkloadOperationWeights {
            get: 2,
            scan: 0,
            delete: 1,
            put: 3,
            merge: 2,
            write_batch: 1,
        };
        for (merge_enabled, expected) in [
            (false, vec![Get, Get, Delete, Put, Put, Put, WriteBatch]),
            (
                true,
                vec![Get, Get, Delete, Put, Put, Put, Merge, Merge, WriteBatch],
            ),
        ] {
            for value in 0..3 * expected.len() as u64 {
                assert_eq!(
                    weights.sample(value, merge_enabled).unwrap(),
                    expected[(value % expected.len() as u64) as usize],
                );
            }
        }
    }

    #[test]
    fn test_put_only_weights_disable_other_operations() {
        let weights = WorkloadOperationWeights {
            put: 3,
            ..NO_OPERATIONS
        };
        for merge_enabled in [false, true] {
            for value in [0, 1, 2, 3, u64::MAX] {
                assert_eq!(weights.sample(value, merge_enabled).unwrap(), Put);
            }
        }
    }

    #[test]
    fn test_operation_weight_examples() {
        const SEED: u64 = 7;
        const SAMPLES: u64 = 100_000;
        let examples = [
            ("puts_only", [0, 0, 0, 1, 0, 0], false),
            ("read_heavy", [3, 0, 0, 1, 0, 0], false),
            ("write_heavy", [1, 0, 0, 3, 0, 0], false),
            ("scan_mix", [6, 2, 1, 1, 0, 0], false),
            ("default_without_merge", [1, 1, 1, 1, 1, 1], false),
            ("default_with_merge", [1, 1, 1, 1, 1, 1], true),
            ("ignored_merge", [3, 0, 0, 1, 100, 0], false),
        ];

        println!("example,seed,samples,get,scan,delete,put,merge,write_batch");
        for (name, [get, scan, delete, put, merge, write_batch], merge_enabled) in examples {
            let weights = WorkloadOperationWeights {
                get,
                scan,
                delete,
                put,
                merge,
                write_batch,
            };
            let rand = DbRand::new(SEED);
            let mut counts = [0u64; 6];
            for _ in 0..SAMPLES {
                let index = match weights
                    .sample(rand.rng().next_u64(), merge_enabled)
                    .unwrap()
                {
                    Get => 0,
                    Scan => 1,
                    Delete => 2,
                    Put => 3,
                    Merge => 4,
                    WriteBatch => 5,
                };
                counts[index] += 1;
            }

            let [get, scan, delete, put, merge, write_batch] = counts;
            println!("{name},{SEED},{SAMPLES},{get},{scan},{delete},{put},{merge},{write_batch}");

            let operations = weights.operations(merge_enabled);
            let total: u64 = operations
                .iter()
                .map(|(_, weight)| u64::from(*weight))
                .sum();
            for (count, (_, weight)) in counts.into_iter().zip(operations) {
                if weight == 0 {
                    assert_eq!(count, 0, "disabled operation selected in {name}");
                } else {
                    let expected = SAMPLES * u64::from(weight) / total;
                    assert!(
                        count.abs_diff(expected) < SAMPLES / 100,
                        "operation count differs from its expected share in {name}"
                    );
                }
            }
        }
    }

    #[test]
    fn test_zero_weights_rejected() {
        let error = WorkloadActor::new(WorkloadActorOptions {
            operation_weights: NO_OPERATIONS,
            ..Default::default()
        })
        .unwrap_err();
        assert_eq!(error.kind(), ErrorKind::Invalid);
    }

    #[test]
    fn test_merge_only_weights_require_merge_operator() {
        let actor = WorkloadActor::new(WorkloadActorOptions {
            operation_weights: WorkloadOperationWeights {
                merge: 1,
                ..NO_OPERATIONS
            },
            ..Default::default()
        })
        .unwrap();
        let weights = &actor.options.operation_weights;
        assert_eq!(
            weights.sample(0, false).unwrap_err().kind(),
            ErrorKind::Invalid
        );
        assert_eq!(weights.sample(u64::MAX, true).unwrap(), Merge);
    }

    #[test]
    fn test_maximum_weights_do_not_overflow() {
        let weights = WorkloadOperationWeights {
            get: u32::MAX,
            scan: u32::MAX,
            delete: u32::MAX,
            put: u32::MAX,
            merge: u32::MAX,
            write_batch: u32::MAX,
        };
        let max = u64::from(u32::MAX);
        for (value, expected) in [
            (0, Get),
            (max - 1, Get),
            (max, Scan),
            (4 * max, Merge),
            (6 * max - 1, WriteBatch),
            (6 * max, Get),
        ] {
            assert_eq!(weights.sample(value, true).unwrap(), expected);
        }
        assert_eq!(weights.sample(5 * max - 1, false).unwrap(), WriteBatch);
        assert_eq!(weights.sample(5 * max, false).unwrap(), Get);
    }

    #[test]
    fn test_put_only_workload_writes_every_step() -> Result<(), Error> {
        struct CheckPuts(WorkloadActor);

        #[async_trait]
        impl Actor for CheckPuts {
            async fn run(&mut self, ctx: &ActorCtx) -> Result<(), Error> {
                for version in 1..=10 {
                    self.0.run(ctx).await?;
                    let value = ctx
                        .db()
                        .get(b"writer/0")
                        .await?
                        .expect("put must write a value");
                    assert_eq!(decode_workload_value(&value), version);
                }
                ctx.shutdown_token().cancel();
                Ok(())
            }
        }

        let actor = WorkloadActor::new(WorkloadActorOptions {
            key_count: 1,
            operation_weights: WorkloadOperationWeights {
                put: 1,
                ..NO_OPERATIONS
            },
            ..Default::default()
        })?;

        Harness::new("put-only", 7, |ctx| async move {
            let db = slatedb::Db::builder(ctx.path().clone(), ctx.main_object_store())
                .with_seed(7)
                .with_system_clock(ctx.system_clock())
                .with_settings(Settings {
                    compactor_options: None,
                    garbage_collector_options: None,
                    ..Default::default()
                })
                .build()
                .await?;
            Ok(Arc::new(db))
        })
        .actor("writer", CheckPuts(actor))
        .run()
    }
}
